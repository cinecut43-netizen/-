// db/registration.js — «выключатель» регистрации новых пользователей.
// Сейчас регистрация ЗАКРЫТА. Войти могут только те, кто уже зарегистрирован.
// Чтобы открыть регистрацию, не меняя код: в Амвере добавьте переменную
// окружения REGISTRATION_OPEN со значением 1 и перезапустите проект.
const MESSAGE =
  'Регистрация новых пользователей временно закрыта — мы готовим запуск. ' +
  'Если вы уже зарегистрированы, войдите по номеру телефона.';

function isClosed() {
  return process.env.REGISTRATION_OPEN !== '1';
}

module.exports = { isClosed: isClosed, MESSAGE: MESSAGE };
